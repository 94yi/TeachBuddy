def render_speech(payload: SpeechGenerate) -> str:
    if payload.occasion == "其他场合":
        return render_other_occasion(payload)
    scenario = SCENARIOS[payload.occasion]
    points = parsed_key_points(payload.key_points)
    audience = payload.audience.strip().rstrip("：:，,。！! ") or scenario["audience"]
    paragraphs = []
    if payload.speaker.strip():
        paragraphs.append("发言人：" + payload.speaker.strip())
    opening = ("借这次" + payload.occasion + "，希望我们把需要了解的事项和需要配合的要求说清楚。下面结合提出的几个要点，与大家作进一步交流。具体安排应以实际确认的要求为准，既不省略必要的说明，也不把尚待商量的措施提前当作定论。"
               if points else scenario["opening"])
    paragraphs.extend([audience + "：", TONE_OPENINGS[payload.tone].format(title=payload.title), opening])
    themes = points[:3] if points else scenario["themes"]
    for index, point in enumerate(themes):
        marker = ("首先", "其次", "还有一点")[index]
        action = CUSTOM_ACTIONS[index] if points else scenario["actions"][index]
        paragraphs.append(marker + "，我们需要关注“" + point.rstrip("。；; ") + "”。" + action)
    if len(points) > 3:
        paragraphs.append("此外，以下几个方面也需要结合实际认真落实：" + "；".join(point.rstrip("。；; ") for point in points[3:]) + "。")
    detail_count = {"short": 0, "medium": 3, "long": 5}[payload.length]
    paragraphs.extend((CUSTOM_DETAILS if points else scenario["details"])[:detail_count])
    if payload.length == "long":
        paragraphs.extend(CUSTOM_LONG_DETAILS if points else LONG_DETAILS[payload.occasion])
    paragraphs.append("希望大家在准确理解这些要点的基础上，结合各自需要承担的事项认真配合。对不清楚的地方及时询问，对需要协调的问题尽早沟通，让要求能够落实到具体行动之中。今天没有明确的措施，还需要进一步商量和确认。" if points else scenario["closing"])
    paragraphs.append({"庄重正式": "我的发言就到这里，谢谢大家！", "亲切自然": "谢谢大家，也期待听到大家的想法！",
                       "鼓舞激励": "让我们带着信心，从具体行动开始。谢谢大家！"}[payload.tone])
    return "\n\n".join(paragraphs) + "\n"


