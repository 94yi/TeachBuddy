def parsed_key_points(value: str) -> list[str]:
    points = []
    for line in value.splitlines():
        point = line.strip()
        # A minus sign attached to a number is content, not a list marker.
        if re.fullmatch(r"[-*•]|\d+[.、）)]|[一二三四五六七八九十]+[、.]", point):
            continue
        point = re.sub(r"^(?:[-*•]\s+|\d+\.\s+|\d+[、）)]\s*|[一二三四五六七八九十]+[、.]\s*)", "", point).strip()
        if point and re.search(r"[\w\u4e00-\u9fff]", point):
            points.append(point)
    return points


